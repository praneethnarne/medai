"""Generate docs/DATASET_CARD.md from the audits and split summaries.

    python backend/src/docs_gen/dataset_card.py

The card is generated rather than written so its numbers cannot drift from the
data. Prose lives here; figures come from results/.
"""

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from data import labels  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[3]


def load(name):
    return (json.loads((ROOT / "results" / f"{name}_audit.json").read_text()),
            json.loads((ROOT / "results" / f"{name}_split_summary.json").read_text()))


def main():
    h, hs = load("ham10000")
    p, ps = load("pad_ufes_20")
    out = []
    w = out.append

    w("""# Dataset card

Generated by `backend/src/docs_gen/dataset_card.py` from `results/*_audit.json` and
`results/*_split_summary.json`. No figure here is typed by hand.

## Why two datasets

MEdAI is for people photographing a mole with a phone. HAM10000 is entirely
dermatoscopic -- taken through a magnifier pressed against the skin under controlled
light -- so a model measured only on it is judged in a setting its users will never be
in. PAD-UFES-20 is smartphone photography, which is the deployment domain.

HAM10000 is too useful to discard and PAD-UFES-20 too small to train on alone, so
HAM10000 is the pretraining corpus and PAD-UFES-20 is where headline numbers are measured.

## At a glance
""")
    w("| | HAM10000 | PAD-UFES-20 |")
    w("|---|---|---|")
    w("| Role | pretraining corpus | **primary domain** |")
    w("| Image type | dermatoscopic | smartphone (clinical close-up) |")
    w(f"| Images | {h['n_images']:,} | {p['n_images']:,} |")
    w(f"| Lesions | {h['n_lesions']:,} | {p['n_lesions']:,} |")
    w(f"| Patients | not recorded | {p['n_patients']:,} |")
    w(f"| Finest split unit | {h['finest_split_unit']} | {p['finest_split_unit']} |")
    w(f"| Licence | {' / '.join(h['licenses'])} | {' / '.join(p['licenses'])} |")
    w(f"| Size on disk | {h['total_bytes'] / 1e6:.0f} MB | {p['total_bytes'] / 1e6:.0f} MB |")
    w("| Source | ISIC collection 212 | ISIC collection 406 |")

    w("""
## Labels

Both collections are served by ISIC under one normalised taxonomy, so no hand-written
class mapping is needed. `diagnosis_1` gives triage, `diagnosis_2` gives lesion type.
`diagnosis_3` is deliberately unused -- it is where the two datasets word the same thing
differently.
""")
    w("| Lesion type | HAM10000 | PAD-UFES-20 | Triage level |")
    w("|---|---:|---:|---|")
    for t in labels.LESION_TYPES:
        a = h["lesion_type_counts"][t]
        b = p["lesion_type_counts"][t]
        note = f"{b:,}" if b else "0 _(HAM only)_"
        w(f"| {labels.DISPLAY_NAMES[t]} | {a:,} | {note} | {labels.TRIAGE_OF_TYPE[t]} |")

    w("\n### Triage distribution\n")
    w("| | " + " | ".join(labels.TRIAGE) + " |")
    w("|---|" + "---:|" * len(labels.TRIAGE))
    for name, a in (("HAM10000", h), ("PAD-UFES-20", p)):
        w(f"| {name} | " + " | ".join(f"{a['triage_counts'][t]:,}" for t in labels.TRIAGE) + " |")

    hb = h["triage_counts"]["benign"] / h["n_images"] * 100
    pm = p["triage_counts"]["malignant"] / p["n_images"] * 100
    w(f"""
**The priors are inverted.** HAM10000 is {hb:.0f}% benign; PAD-UFES-20 is {pm:.0f}%
malignant, because it comes from a screening programme where people presented with
something that worried them. Cross-domain degradation will therefore have two causes --
images that look different, and base rates that differ -- and they must be separated
before the headline number means anything.

## Splits
""")
    for name, s in (("HAM10000", hs), ("PAD-UFES-20", ps)):
        w(f"\n**{name}** — split at {s['split_unit']} level, seed {s['seed']}\n")
        w(f"| Split | Images | Share | {s['split_unit'].capitalize()}s |")
        w("|---|---:|---:|---:|")
        for k in ("train", "val", "test"):
            v = s["splits"][k]
            w(f"| {k} | {v['n_images']:,} | {v['share'] * 100:.1f}% | {v['n_groups']:,} |")

    mel_test = ps["splits"]["test"]["lesion_type"].get("melanoma", 0)
    fitz = p["fitzpatrick_counts"]
    dark = fitz.get("V", 0) + fitz.get("VI", 0)
    recorded = p["n_images"] - fitz.get("unrecorded", 0)
    w(f"""
Split at the finest unit each dataset supports, so two photographs of one lesion cannot
land on opposite sides. HAM10000 records no patient id, so lesion level is the best
available there -- two lesions from one patient may still be separated. A known,
documented limitation rather than an oversight.

## Known limitations

**Melanoma is nearly absent from the primary domain.** PAD-UFES-20 holds
{p['lesion_type_counts']['melanoma']} melanoma images; {mel_test} are in the test split.
A per-class recall on {mel_test} examples swings about 25 points when one image changes,
so it cannot carry a conclusion. This is why triage is the primary task, and why melanoma
recall is only reported with a confidence interval and its support count.

**Skin tone is barely represented.** Fitzpatrick type is recorded for {recorded:,} of
{p['n_images']:,} PAD-UFES-20 images, but types V and VI total {dark}. Comparison across
I-III versus IV+ is possible; claims about dark skin are not, and will not be made.
HAM10000 records no skin tone at all.

**HAM10000 is not the canonical 10,015 images.** ISIC's collection contains
{h['n_images']:,} -- the original release plus the ISIC 2018 validation and test sets,
labelled afterwards. Our HAM10000 numbers are therefore **not comparable to published
HAM10000 results**.

**Licensing.** HAM10000 is CC-BY-NC. As the pretraining corpus, it passes that
non-commercial restriction to every model trained here.
""")

    path = ROOT / "docs" / "DATASET_CARD.md"
    path.write_text("\n".join(out) + "\n")
    print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
